// EXACT soft-float x87 unit — implements x87_exact.h on top of Berkeley SoftFloat-3e
// (extF80, 8086 specialization).  See the header for the contract; this file also
// hosts the X87Exec dispatch that selects NATIVE (host x87) or EXACT at runtime.
//
// ---------------------------------------------------------------------------------
// BEHAVIOR SOURCES.  Everything "undefined" in the SDM was pinned by running the
// actual instruction on this host (scratchpad probe, session 24) and is reproduced
// exactly:
//   - fnsave pad words: the high 16 bits of the CW/SW/TW dwords read 0xFFFF.
//   - fnsave REGENERATES the tag word from the register contents for every
//     non-empty register (P6+ keeps only an empty bit internally); empty registers
//     keep tag 11 and their raw bytes.
//   - SW.ES and SW.B are DERIVED: ES = ((flags & ~masks) & 0x3F) != 0, B = ES.
//     A stored ES bit inconsistent with the flags is ignored by frstor (probed:
//     ES=1/flags=0 image does not fault and saves back ES=0; PE=1-unmasked/ES=0
//     image DOES fault at the next waiting instruction).
//   - fldcw normalization: CW := (value & 0x1F3F) | 0x0040 (bit 6 forced, 13-15 and
//     7 cleared).
//   - #MF delivery is DEFERRED: an op that raises a new unmasked exception COMPLETES
//     (flags + ES recorded, result delivered per the abort/deferred-store rules) and
//     the fault materializes at the NEXT waiting fp instruction.  The EXACT unit
//     returns -1 from that next op (image untouched), mirroring the native thunk
//     whose frstor+INSN faults there.  fwait delivers likewise.  No-wait forms
//     (fnstsw, fnstcw, fnclex) execute despite a pending exception.
//   - condition codes: arithmetic/store/round ops write C1 = "significand was
//     incremented by rounding" (0 when exact or aborted) and PRESERVE C0/C2/C3;
//     loads/fxch/fchs/fabs/ffree/constants clear C1 and preserve the rest;
//     compares/ftst/fxam write all four; fnstsw/fnstcw/fldcw/fnclex/fwait preserve
//     all four.  Masked stack overflow sets C1=1, underflow C1=0.
//   - the constant loads (fldpi/fldlg2/fldln2/fldl2e) honor RC: the internal
//     values carry >64 significant bits with a guard bit of 1 and nonzero sticky,
//     so RN and +inf round the 64-bit base up, -inf and chop truncate (positive
//     constants).  Host-verified patterns (RN): pi=4000:C90FDAA22168C235,
//     lg2=3FFD:9A209A84FBCFF799, ln2=3FFE:B17217F7D1CF79AC,
//     l2e=3FFF:B8AA3B295C17F0BC.  No flags, C1=0.
//   - masked responses (probed): underflow on a register op writes the real
//     indefinite (FFFF:C000...0) over the destination and still pops; stores from an
//     empty ST0 write the format indefinite to memory and still pop; overflow on a
//     push decrements TOP and writes the indefinite.  fst m32/m64 of an extended
//     denormal raises U/P but NOT D.  fist invalid (out of range / NaN) raises IE
//     only (no PE) and stores the integer indefinite.
//   - unmasked O/U on a REGISTER destination store the result with the exponent
//     wrapped by -/+24576 (probed via fscale: 2^16383*2^1000 unmasked -> 23E6:8000,
//     i.e. biased 17383+16383-24576); on a MEMORY store nothing is stored and the
//     stack does not pop.
//
// PRECISION CONTROL (CW.PC -> extF80_roundingPrecision) applies ONLY to
// add/sub/mul/div/sqrt — never to loads, stores, conversions, frndint, fscale or
// the transcendentals (probed: fld under PC=32 copies all 64 bits).  PC=01
// (reserved) is treated as 64-bit and never generated by the corpus.
//
// TRANSCENDENTALS (fsin/fcos/fsincos/fpatan/fyl2x/f2xm1) are DETERMINISTIC pure
// integer/extF80 code, close to but not bit-equal with silicon (accepted design,
// see x87_exact.h).  Methods:
//   - fsin/fcos/fsincos: argument reduction modulo the x87's own 66-bit pi/2
//     (0xC90FDAA22168C234C x 2^-65, exactly the value silicon uses, so even huge
//     arguments track the hardware's "wrong" pi) performed EXACTLY in 192-bit
//     integer fixed point (x*2^127 long-divided by pi/2*2^127, nearest quotient,
//     exact remainder), then odd/even Taylor kernels of degree 21/22 on
//     |r| <= pi/4 evaluated in extF80 (round-nearest, 80-bit) — kernel error
//     ~2^-72, well under 1 ulp.  |x| >= 2^63: C2=1, operand untouched (hardware
//     rule).  All internal arithmetic uses fixed RN/80 so the guest RC never
//     influences the result (documented divergence: hardware rounds the final
//     result per RC; ours is the RN value).
//   - fpatan: atan2 special cases use the RN-rounded pi family; the kernel halves
//     the argument four times via u' = u/(1+sqrt(1+u^2)) then applies an odd
//     Taylor polynomial of degree 15 and multiplies by 16 (error ~2^-74).
//   - fyl2x: log2(m) for m in [sqrt2/2, sqrt2) via the atanh series
//     s=(m-1)/(m+1), 2/ln2 * sum s^(2k+1)/(2k+1) to k=13 (~2^-78), plus the
//     exponent; multiplied by y in extF80.
//   - f2xm1: 2^x-1 = expm1(x*ln2) by a degree-20 Taylor kernel (~2^-76 for
//     |x| <= 1; outside the SDM-defined domain the same series runs anyway —
//     deterministic, finite, explicitly "undefined" territory).
//   - flags: PE on every inexact numeric path, DE for denormal inputs, UE when the
//     delivered result is denormal, IE/indefinite for the invalid cases; C1=0
//     (hardware's per-result roundup bit cannot be reproduced without bit-equal
//     results); fsin/fcos/fsincos write C2 (0 reduced, 1 unreduced), the rest
//     preserve it.
// ---------------------------------------------------------------------------------
