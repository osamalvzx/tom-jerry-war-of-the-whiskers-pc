int X87ExactExec(CpuState& s, uint8_t op, uint8_t modrm, uint32_t ea) {
    InitTrans();

    // ---- deferred #MF delivery: pending unmasked exception + waiting instruction
    uint16_t rawCw, rawSw;
    memcpy(&rawCw, s.fpu.image + 0, 2);
    memcpy(&rawSw, s.fpu.image + 4, 2);
    bool pending = ((rawSw & ~rawCw) & 0x3F) != 0;
    if (op == 0x9B) {
        if (pending) return -1;
        Exec E{}; LoadImage(E.F, s.fpu.image); StoreImage(E.F, s.fpu.image);
        return 1;                                  // fnsave-equivalent renormalize
    }
    if (op < 0xD8 || op > 0xDF) return 0;
    const int mod = modrm >> 6, reg = (modrm >> 3) & 7, rm = modrm & 7;
    const bool noWait = (op == 0xDF && modrm == 0xE0) || (op == 0xDB && modrm == 0xE2) ||
                        (mod != 3 && reg == 7 && (op == 0xD9 || op == 0xDD));
    if (pending && !noWait) return -1;             // image untouched, like the thunk

    Exec E{};
    LoadImage(E.F, s.fpu.image);
    Fpu& F = E.F;
    const uint8_t grc = F.SfRound();
    bool decoded = true;

    // load a memory f32/f64 operand for arithmetic: returns false on unmasked abort
    // (flags already raised); cls/den out-params feed the shared gates
    // For ARITHMETIC uses the converted operand must stay SIGNALING when the raw
    // f32/f64 was an SNaN (the conversion quietens it): the x87's two-NaN rule
    // prefers a QNaN over an SNaN operand, which the softfloat propagation only
    // reproduces if it sees the SNaN as such.  (fld itself pushes the QUIET form.)
    auto LoadMemF32 = [&](extFloat80_t* out, Cls* cls) {
        uint32_t u = Exec::Ld32(ea);
        *cls = ClassF32(u);
        softfloat_exceptionFlags = 0;
        float32_t f; f.v = u;
        *out = f32_to_extF80(f);
        softfloat_exceptionFlags = 0;
        if (*cls == cSNaN) out->signif &= ~0x4000000000000000ull;
        return true;
    };
    auto LoadMemF64 = [&](extFloat80_t* out, Cls* cls) {
        uint64_t u = Exec::Ld64(ea);
        *cls = ClassF64(u);
        softfloat_exceptionFlags = 0;
        float64_t f; f.v = u;
        *out = f64_to_extF80(f);
        softfloat_exceptionFlags = 0;
        if (*cls == cSNaN) out->signif &= ~0x4000000000000000ull;
        return true;
    };

    // shared "binary arithmetic with a memory/int operand already converted" —
    // ST0 is dst; cb is the RAW class of the memory bits (drives #IA/#D)
    auto MemArith = [&](int kind, extFloat80_t b, Cls cb) {
        // kind: 0 add,1 mul,2 com,3 comp,4 sub,5 subr,6 div,7 divr
        bool e0 = F.Empty(0);
        extFloat80_t a = e0 ? kIndef : F.Get(0);
        Cls ca = e0 ? cQNaN : ClassOf(a);
        int em = e0 ? 1 : 0;
        uint8_t prec = F.Prec();
        switch (kind) {
        case 2: case 3:
            E.CompareOp(a, b, ca, cb, em, kind == 3 ? 1 : 0, false); return;
        case 0: E.BinaryOp(extF80_add, wAddSub, a, b, ca, cb, em, 0, 0, prec); return;
        case 1: E.BinaryOp(extF80_mul, wMul,    a, b, ca, cb, em, 0, 0, prec); return;
        case 4: E.BinaryOp(extF80_sub, wAddSub, a, b, ca, cb, em, 0, 0, prec); return;
        case 5: E.BinaryOp(extF80_sub, wAddSub, b, a, cb, ca, em, 0, 0, prec); return;
        case 6: E.BinaryOp(extF80_div, wDiv,    a, b, ca, cb, em, 0, 0, prec); return;
        default: E.BinaryOp(extF80_div, wDiv,   b, a, cb, ca, em, 0, 0, prec); return;
        }
    };

    // register-form binary: a = ST0, b = ST(i)
    auto RegArith = [&](int kind, int srcI, int dst, int pops) {
        bool eA = F.Empty(0), eB = F.Empty(srcI);
        extFloat80_t a = eA ? kIndef : F.Get(0);
        extFloat80_t b = eB ? kIndef : F.Get(srcI);
        Cls ca = ClassOf(a), cb = ClassOf(b);
        int em = (eA || eB) ? 1 : 0;
        uint8_t prec = F.Prec();
        switch (kind) {
        case 0: E.BinaryOp(extF80_add, wAddSub, a, b, ca, cb, em, dst, pops, prec); break;
        case 1: E.BinaryOp(extF80_mul, wMul,    a, b, ca, cb, em, dst, pops, prec); break;
        case 4: E.BinaryOp(extF80_sub, wAddSub, a, b, ca, cb, em, dst, pops, prec); break;  // ST0 - ST(i)
        case 5: E.BinaryOp(extF80_sub, wAddSub, b, a, cb, ca, em, dst, pops, prec); break;  // ST(i) - ST0
        case 6: E.BinaryOp(extF80_div, wDiv,    a, b, ca, cb, em, dst, pops, prec); break;  // ST0 / ST(i)
        default: E.BinaryOp(extF80_div, wDiv,   b, a, cb, ca, em, dst, pops, prec); break;  // ST(i) / ST0
        }
    };

    // fst/fstp to f32/f64 memory
    auto StoreMemFp = [&](bool dbl, bool pop) {
        F.c1 = 0;
        if (F.Empty(0)) {
            if (!E.StackFault(false)) return;
            if (dbl) Exec::St64(ea, 0xFFF8000000000000ull);
            else     Exec::St32(ea, 0xFFC00000u);
            if (pop) F.PopOne();
            return;
        }
        extFloat80_t v = F.Get(0);
        softfloat_roundingMode = grc; extF80_roundingPrecision = 80;
        softfloat_exceptionFlags = 0;
        uint64_t bits; uint8_t sf;
        if (dbl) { float64_t r = extF80_to_f64(v); bits = r.v; sf = (uint8_t)softfloat_exceptionFlags; }
        else     { float32_t r = extF80_to_f32(v); bits = r.v; sf = (uint8_t)softfloat_exceptionFlags; }
        bool up = false;
        if (sf & softfloat_flag_inexact) {
            softfloat_roundingMode = softfloat_round_minMag; softfloat_exceptionFlags = 0;
            uint64_t tb;
            if (dbl) { float64_t r = extF80_to_f64(v); tb = r.v; }
            else     { float32_t r = extF80_to_f32(v); tb = r.v; }
            uint64_t magMask = dbl ? 0x7FFFFFFFFFFFFFFFull : 0x7FFFFFFFull;
            up = (bits & magMask) > (tb & magMask);
        }
        softfloat_exceptionFlags = 0;
        uint16_t xf = X87FlagsFromSf(sf);
        if (xf & kIE) {                            // SNaN (or unsupported) source
            F.flags |= kIE;
            if (!F.Masked(kIE)) return;
            if (dbl) Exec::St64(ea, bits); else Exec::St32(ea, (uint32_t)bits);
            if (pop) F.PopOne();
            return;
        }
        // unmasked O/U on a memory store: nothing is stored, the stack does not
        // pop, and only the O/U flag is recorded (no PE — probed).  Unmasked #U
        // fires on tininess alone, even for an exactly-representable denormal.
        bool tinyStore = dbl ? (!(bits & 0x7FF0000000000000ull) && (bits & 0xFFFFFFFFFFFFFull))
                             : (!(bits & 0x7F800000u) && (bits & 0x7FFFFFu));
        if ((xf & kOE) && !F.Masked(kOE)) {
            F.flags |= kOE;
            return;
        }
        if (((xf & kUE) || tinyStore) && !F.Masked(kUE)) {
            F.flags |= kUE;
            return;
        }
        F.flags |= xf;
        if (dbl) Exec::St64(ea, bits); else Exec::St32(ea, (uint32_t)bits);
        F.c1 = up ? 1 : 0;
        if (pop) F.PopOne();
    };

    // fist/fistp
    auto StoreMemInt = [&](int size, bool pop) {   // size 16/32/64
        F.c1 = 0;
        if (F.Empty(0)) {
            if (!E.StackFault(false)) return;
            if (size == 16) Exec::St16(ea, 0x8000);
            else if (size == 32) Exec::St32(ea, 0x80000000u);
            else Exec::St64(ea, 0x8000000000000000ull);
            if (pop) F.PopOne();
            return;
        }
        extFloat80_t v = F.Get(0);
        IntCvt c = (size == 64) ? CvtToI64(v, grc) : CvtToI32(v, grc);
        bool inv = c.invalid;
        if (size == 16 && !inv) {
            int64_t x = (int64_t)c.val;
            if (x < -32768 || x > 32767) inv = true;
        }
        if (inv) {                                 // IE only — PE discarded (probed)
            F.flags |= kIE;
            if (!F.Masked(kIE)) return;
            if (size == 16) Exec::St16(ea, 0x8000);
            else if (size == 32) Exec::St32(ea, 0x80000000u);
            else Exec::St64(ea, 0x8000000000000000ull);
            if (pop) F.PopOne();
            return;
        }
        if (c.inexact) F.flags |= kPE;
        if (size == 16) Exec::St16(ea, (uint16_t)c.val);
        else if (size == 32) Exec::St32(ea, (uint32_t)c.val);
        else Exec::St64(ea, c.val);
        F.c1 = c.up ? 1 : 0;
        if (pop) F.PopOne();
    };

    // fild (exact)
    auto LoadInt = [&](int64_t v) {
        F.c1 = 0;
        int pc = E.PushCheck();
        if (pc != 2) return;
        softfloat_exceptionFlags = 0;
        E.PushVal(i64_to_extF80(v));
        softfloat_exceptionFlags = 0;
    };

    // in-place unary underflow (fchs/fabs/frndint/fsqrt/transcendental prologue)
    auto Underflow0 = [&]() {                      // returns true if masked-handled
        if (!E.StackFault(false)) return false;
        F.Put(0, kIndef);
        return true;
    };

    switch (op) {
    // ------------------------------------------------------------------ D8
    case 0xD8:
        if (mod != 3) {
            extFloat80_t b; Cls cb;
            LoadMemF32(&b, &cb);
            MemArith(reg, b, cb);
        } else {
            if (reg == 2 || reg == 3) {            // fcom/fcomp st(i)
                bool em = F.Empty(0) || F.Empty(rm);
                extFloat80_t a = em ? kIndef : F.Get(0), b = em ? kIndef : F.Get(rm);
                E.CompareOp(a, b, ClassOf(a), ClassOf(b), em ? 1 : 0,
                            reg == 3 ? 1 : 0, false);
            } else {
                RegArith(reg, rm, 0, 0);           // fadd/fmul/fsub/fsubr/fdiv/fdivr st,st(i)
            }
        }
        break;

    // ------------------------------------------------------------------ D9
    case 0xD9:
        if (mod != 3) {
            switch (reg) {
            case 0: {                              // fld m32
                F.c1 = 0;
                int pc = E.PushCheck();
                if (pc != 2) break;
                uint32_t u = Exec::Ld32(ea);
                Cls c = ClassF32(u);
                softfloat_exceptionFlags = 0;
                float32_t f; f.v = u;
                extFloat80_t v = f32_to_extF80(f);
                uint8_t sf = (uint8_t)softfloat_exceptionFlags;
                softfloat_exceptionFlags = 0;
                if (c == cDenorm) { if (!E.DenormGate()) break; }
                if (sf & softfloat_flag_invalid) {
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                }
                E.PushVal(v);
                break;
            }
            case 2: StoreMemFp(false, false); break;   // fst m32
            case 3: StoreMemFp(false, true); break;    // fstp m32
            case 5:                                     // fldcw
                F.cw = (Exec::Ld16(ea) & 0x1F3F) | 0x0040;
                break;
            case 7:                                     // fnstcw
                Exec::St16(ea, F.cw);
                break;
            default: decoded = false; break;            // fldenv/fnstenv/D9 /1
            }
        } else {
            switch (modrm) {
            case 0xC0: case 0xC1: case 0xC2: case 0xC3:
            case 0xC4: case 0xC5: case 0xC6: case 0xC7: {   // fld st(i)
                // source-EMPTY is checked before dest-overflow (probed: empty
                // source + occupied dest -> C1=0 underflow, indefinite pushed)
                F.c1 = 0;
                if (F.Empty(rm)) {
                    if (!E.StackFault(false)) break;
                    F.PushSlot(); F.Put(0, kIndef);
                    break;
                }
                extFloat80_t v = F.Get(rm);
                int pc = E.PushCheck();
                if (pc != 2) break;
                E.PushVal(v);
                break;
            }
            case 0xC8: case 0xC9: case 0xCA: case 0xCB:
            case 0xCC: case 0xCD: case 0xCE: case 0xCF: {   // fxch st(i)
                F.c1 = 0;
                bool e0 = F.Empty(0), ei = F.Empty(rm);
                if (e0 || ei) {
                    if (!E.StackFault(false)) break;
                    if (e0) F.Put(0, kIndef);
                    if (ei) F.Put(rm, kIndef);
                }
                extFloat80_t a = F.Get(0), b = F.Get(rm);
                F.Put(0, b); F.Put(rm, a);
                break;
            }
            case 0xE0:                                       // fchs
            case 0xE1: {                                     // fabs
                F.c1 = 0;
                if (F.Empty(0)) { Underflow0(); break; }
                extFloat80_t v = F.Get(0);
                if (modrm == 0xE0) v.signExp ^= 0x8000;
                else v.signExp &= 0x7FFF;
                F.Put(0, v);
                break;
            }
            case 0xE4: {                                     // ftst
                bool em = F.Empty(0);
                extFloat80_t a = em ? kIndef : F.Get(0);
                E.CompareOp(a, MakeExt(0, 0), ClassOf(a), cZero, em ? 1 : 0, 0, false);
                break;
            }
            case 0xE5: {                                     // fxam
                extFloat80_t v = F.r[F.Phys(0)];
                F.c1 = (v.signExp >> 15) & 1;
                if (F.Empty(0)) { F.c3 = 1; F.c2 = 0; F.c0 = 1; break; }
                switch (ClassOf(v)) {
                case cNorm:   F.c3 = 0; F.c2 = 1; F.c0 = 0; break;
                case cInf:    F.c3 = 0; F.c2 = 1; F.c0 = 1; break;
                case cZero:   F.c3 = 1; F.c2 = 0; F.c0 = 0; break;
                case cDenorm: F.c3 = 1; F.c2 = 1; F.c0 = 0; break;
                case cQNaN: case cSNaN: F.c3 = 0; F.c2 = 0; F.c0 = 1; break;
                default:      F.c3 = 0; F.c2 = 0; F.c0 = 0; break;   // unsupported
                }
                break;
            }
            case 0xE8: case 0xEA: case 0xEB: case 0xEC: case 0xED: case 0xEE: {
                // fld1 / fldl2e / fldpi / fldlg2 / fldln2 / fldz — RC-rounded
                F.c1 = 0;
                int pc = E.PushCheck();
                if (pc != 2) break;
                int rc = F.Rc();
                int up = (rc == 0 || rc == 2) ? 1 : 0;       // guard=1, sticky=1
                extFloat80_t v;
                switch (modrm) {
                case 0xE8: v = kOne; break;
                case 0xEA: v = MakeExt(0x3FFF, 0xB8AA3B295C17F0BBull + up); break;
                case 0xEB: v = MakeExt(0x4000, 0xC90FDAA22168C234ull + up); break;
                case 0xEC: v = MakeExt(0x3FFD, 0x9A209A84FBCFF798ull + up); break;
                case 0xED: v = MakeExt(0x3FFE, 0xB17217F7D1CF79ABull + up); break;
                default:   v = MakeExt(0, 0); break;
                }
                E.PushVal(v);
                break;
            }
            case 0xFA: {                                     // fsqrt
                F.c1 = 0;
                if (F.Empty(0)) { Underflow0(); break; }
                extFloat80_t a = F.Get(0);
                Cls ca = ClassOf(a);
                if (ca == cUnsupp) {
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                    F.Put(0, kIndef); break;
                }
                // negative operand: the invalid path exits before the denormal
                // check (probed: fsqrt(-denormal) -> IE only, no DE)
                bool negNonzero = (a.signExp >> 15) && !(ca == cZero);
                if (ca == cDenorm && !negNonzero && !E.DenormGate()) break;
                extFloat80_t out;
                auto sq = [](extFloat80_t x, extFloat80_t) { return extF80_sqrt(x); };
                if (!E.Deliver((BinFn)+sq, wMul, a, a, F.Prec(), &out)) break;
                F.Put(0, out);
                break;
            }
            case 0xFC: {                                     // frndint
                F.c1 = 0;
                if (F.Empty(0)) { Underflow0(); break; }
                extFloat80_t a = F.Get(0);
                Cls ca = ClassOf(a);
                if (ca == cUnsupp) {
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                    F.Put(0, kIndef); break;
                }
                if (ca == cDenorm && !E.DenormGate()) break;
                softfloat_roundingMode = grc; softfloat_exceptionFlags = 0;
                extFloat80_t r = extF80_roundToInt(a, grc, true);
                uint8_t sf = (uint8_t)softfloat_exceptionFlags;
                bool up = false;
                if (sf & softfloat_flag_inexact) {
                    softfloat_exceptionFlags = 0;
                    extFloat80_t t = extF80_roundToInt(a, softfloat_round_minMag, false);
                    up = MagGT(r, t);
                }
                softfloat_exceptionFlags = 0;
                if (sf & softfloat_flag_invalid) {           // SNaN
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                    F.Put(0, r); break;
                }
                if (sf & softfloat_flag_inexact) F.flags |= kPE;
                F.Put(0, r); F.c1 = up ? 1 : 0;
                break;
            }
            case 0xFD: {                                     // fscale
                F.c1 = 0;
                bool e0 = F.Empty(0), e1 = F.Empty(1);
                if (e0 || e1) {
                    if (!E.StackFault(false)) break;
                    F.Put(0, kIndef); break;
                }
                extFloat80_t a = F.Get(0), b = F.Get(1);
                Cls ca = ClassOf(a), cb = ClassOf(b);
                if (ca == cUnsupp || cb == cUnsupp) {
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                    F.Put(0, kIndef); break;
                }
                if (IsNaNC(ca) || IsNaNC(cb)) {              // propagate x87-style
                    softfloat_exceptionFlags = 0;
                    extFloat80_t r = extF80_mul(a, b);
                    bool inv = (softfloat_exceptionFlags & softfloat_flag_invalid) != 0;
                    softfloat_exceptionFlags = 0;
                    if (inv) {
                        F.flags |= kIE;
                        if (!F.Masked(kIE)) break;
                    }
                    F.Put(0, r); break;
                }
                if ((ca == cDenorm || cb == cDenorm) && !E.DenormGate()) break;
                if (cb == cInf) {
                    bool bneg = (b.signExp >> 15) & 1;
                    if (!bneg) {                             // * 2^+inf
                        if (ca == cZero) {
                            F.flags |= kIE;
                            if (!F.Masked(kIE)) break;
                            F.Put(0, kIndef); break;
                        }
                        F.Put(0, MakeExt((uint16_t)((a.signExp & 0x8000) | 0x7FFF),
                                         0x8000000000000000ull));
                        break;
                    } else {                                 // * 2^-inf
                        if (ca == cInf) {
                            F.flags |= kIE;
                            if (!F.Masked(kIE)) break;
                            F.Put(0, kIndef); break;
                        }
                        F.Put(0, MakeExt((uint16_t)(a.signExp & 0x8000), 0));
                        break;
                    }
                }
                if (ca == cZero || ca == cInf) { F.Put(0, a); break; }
                // n = ST1 truncated toward zero, clamped (saturates identically)
                int32_t n = 0;
                {
                    int be = b.signExp & 0x7FFF;
                    bool bneg = (b.signExp >> 15) & 1;
                    if (cb != cZero) {
                        int e = be - 0x3FFF;
                        uint64_t bs = b.signif;
                        if (be == 0) e = -0x3FFF;            // denormal: |b| < 1 -> 0
                        if (e >= 0) {
                            uint64_t mag = (e >= 63) ? 0xFFFFFFFFFFFFFFFFull
                                                     : (bs >> (63 - e));
                            n = (mag > 80000) ? 80000 : (int32_t)mag;
                            if (bneg) n = -n;
                        }
                    }
                }
                // unpack ST0, single rounding at exp+n
                int exp = a.signExp & 0x7FFF; uint64_t sig = a.signif;
                bool sign = (a.signExp >> 15) & 1;
                if (!exp) exp = 1;
                if (!(sig >> 63)) {
                    struct exp32_sig64 nz = softfloat_normSubnormalExtF80Sig(sig);
                    exp += nz.exp; sig = nz.sig;
                }
                auto scaleRun = [&](int32_t nn, uint8_t mode, uint8_t* sfOut) {
                    softfloat_roundingMode = mode;
                    extF80_roundingPrecision = 80;
                    softfloat_exceptionFlags = 0;
                    extFloat80_t r = softfloat_roundPackToExtF80(sign, exp + nn, sig, 0, 80);
                    *sfOut = (uint8_t)softfloat_exceptionFlags;
                    softfloat_exceptionFlags = 0;
                    return r;
                };
                uint8_t sf;
                extFloat80_t r = scaleRun(n, grc, &sf);
                bool up = false;
                if (sf & softfloat_flag_inexact) {
                    uint8_t sf2;
                    extFloat80_t t = scaleRun(n, softfloat_round_minMag, &sf2);
                    up = MagGT(r, t);
                }
                uint16_t xf = X87FlagsFromSf(sf);
                bool tiny = ((r.signExp & 0x7FFF) == 0) && r.signif;
                if ((xf & kOE) && !F.Masked(kOE)) {
                    uint8_t sfw; extFloat80_t w = scaleRun(n - 24576, grc, &sfw);
                    uint8_t sfw2; extFloat80_t w2 = scaleRun(n - 24576, softfloat_round_minMag, &sfw2);
                    F.flags |= kOE | (X87FlagsFromSf(sfw) & kPE);   // wrapped rounding's PE
                    F.Put(0, w); F.c1 = MagGT(w, w2) ? 1 : 0;
                    break;
                }
                if (!F.Masked(kUE) && ((xf & kUE) || tiny)) {
                    uint8_t sfw; extFloat80_t w = scaleRun(n + 24576, grc, &sfw);
                    uint8_t sfw2; extFloat80_t w2 = scaleRun(n + 24576, softfloat_round_minMag, &sfw2);
                    F.flags |= kUE | (X87FlagsFromSf(sfw) & kPE);
                    F.Put(0, w); F.c1 = MagGT(w, w2) ? 1 : 0;
                    break;
                }
                F.flags |= xf;
                F.Put(0, r); F.c1 = up ? 1 : 0;
                break;
            }
            // ------------------------- transcendentals -------------------------
            case 0xF0: {                                     // f2xm1
                F.c1 = 0;
                if (F.Empty(0)) { Underflow0(); break; }
                extFloat80_t a = F.Get(0);
                Cls ca = ClassOf(a);
                if (ca == cUnsupp) {
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                    F.Put(0, kIndef); break;
                }
                if (ca == cSNaN) {
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                    F.Put(0, Quieten(a)); break;
                }
                if (ca == cQNaN) { F.Put(0, a); break; }
                if (ca == cZero) { F.Put(0, a); break; }
                if (ca == cInf) {
                    if (a.signExp >> 15) F.Put(0, Neg(kOne));    // 2^-inf - 1 = -1
                    else F.Put(0, a);
                    break;
                }
                if (ca == cDenorm && !E.DenormGate()) break;
                // out of the defined domain (|x| > 1): this host passes the
                // operand through unchanged with PE (probed; SDM: "undefined")
                if ((a.signExp & 0x7FFF) > 0x3FFF ||
                    ((a.signExp & 0x7FFF) == 0x3FFF && a.signif > 0x8000000000000000ull)) {
                    F.flags |= kPE;
                    F.Put(0, a);
                    break;
                }
                TransEnv();
                extFloat80_t r = Expm1Pow2(a);
                softfloat_exceptionFlags = 0;
                F.flags |= kPE;
                if (((r.signExp & 0x7FFF) == 0) && r.signif) F.flags |= kUE;
                F.Put(0, r);
                break;
            }
            case 0xF1: {                                     // fyl2x
                F.c1 = 0;
                bool e0 = F.Empty(0), e1 = F.Empty(1);
                if (e0 || e1) {
                    if (!E.StackFault(false)) break;
                    F.Put(1, kIndef); F.PopOne(); break;
                }
                extFloat80_t x = F.Get(0), y = F.Get(1);
                Cls cx = ClassOf(x), cy = ClassOf(y);
                if (cx == cUnsupp || cy == cUnsupp) {
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                    F.Put(1, kIndef); F.PopOne(); break;
                }
                if (IsNaNC(cx) || IsNaNC(cy)) {
                    softfloat_exceptionFlags = 0;
                    extFloat80_t r = extF80_mul(x, y);
                    bool inv = (softfloat_exceptionFlags & softfloat_flag_invalid) != 0;
                    softfloat_exceptionFlags = 0;
                    if (inv) { F.flags |= kIE; if (!F.Masked(kIE)) break; }
                    F.Put(1, r); F.PopOne(); break;
                }
                if ((cx == cDenorm || cy == cDenorm) && !E.DenormGate()) break;
                bool xs = (x.signExp >> 15) & 1, ys = (y.signExp >> 15) & 1;
                if (cx == cZero) {
                    if (cy == cZero) {
                        F.flags |= kIE;
                        if (!F.Masked(kIE)) break;
                        F.Put(1, kIndef); F.PopOne(); break;
                    }
                    F.flags |= kZE;                          // y * -inf
                    if (!F.Masked(kZE)) break;
                    F.Put(1, MakeExt((uint16_t)((ys ? 0 : 0x8000) | 0x7FFF),
                                     0x8000000000000000ull));
                    F.PopOne(); break;
                }
                if (xs) {                                    // negative x
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                    F.Put(1, kIndef); F.PopOne(); break;
                }
                bool xIsOne = (x.signExp == 0x3FFF) && (x.signif == 0x8000000000000000ull);
                if (xIsOne) {
                    if (cy == cInf) {
                        F.flags |= kIE;
                        if (!F.Masked(kIE)) break;
                        F.Put(1, kIndef); F.PopOne(); break;
                    }
                    F.Put(1, MakeExt((uint16_t)(ys ? 0x8000 : 0), 0)); F.PopOne(); break;
                }
                if (cx == cInf) {
                    if (cy == cZero) {
                        F.flags |= kIE;
                        if (!F.Masked(kIE)) break;
                        F.Put(1, kIndef); F.PopOne(); break;
                    }
                    F.Put(1, MakeExt((uint16_t)((ys ? 0x8000 : 0) | 0x7FFF),
                                     0x8000000000000000ull));
                    F.PopOne(); break;
                }
                if (cy == cZero || cy == cInf) {
                    // sign of log2(x): x > 1 -> +, x < 1 -> -
                    bool lneg = (x.signExp & 0x7FFF) < 0x3FFF;
                    uint16_t sgn = (uint16_t)(((ys ? 1 : 0) ^ (lneg ? 1 : 0)) ? 0x8000 : 0);
                    if (cy == cZero) { F.Put(1, MakeExt(sgn, 0)); F.PopOne(); break; }
                    F.Put(1, MakeExt((uint16_t)(sgn | 0x7FFF), 0x8000000000000000ull));
                    F.PopOne(); break;
                }
                TransEnv();
                extFloat80_t L = Log2Pos(x);
                softfloat_exceptionFlags = 0;
                extFloat80_t r = extF80_mul(y, L);
                uint16_t xf = X87FlagsFromSf((uint8_t)softfloat_exceptionFlags);
                softfloat_exceptionFlags = 0;
                F.flags |= kPE | (xf & (kOE | kUE));
                F.Put(1, r); F.PopOne();
                break;
            }
            case 0xF3: {                                     // fpatan: atan2(ST1, ST0)
                F.c1 = 0;
                bool e0 = F.Empty(0), e1 = F.Empty(1);
                if (e0 || e1) {
                    if (!E.StackFault(false)) break;
                    F.Put(1, kIndef); F.PopOne(); break;
                }
                extFloat80_t x = F.Get(0), y = F.Get(1);
                Cls cx = ClassOf(x), cy = ClassOf(y);
                if (cx == cUnsupp || cy == cUnsupp) {
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                    F.Put(1, kIndef); F.PopOne(); break;
                }
                if (IsNaNC(cx) || IsNaNC(cy)) {
                    softfloat_exceptionFlags = 0;
                    extFloat80_t r = extF80_mul(x, y);
                    bool inv = (softfloat_exceptionFlags & softfloat_flag_invalid) != 0;
                    softfloat_exceptionFlags = 0;
                    if (inv) { F.flags |= kIE; if (!F.Masked(kIE)) break; }
                    F.Put(1, r); F.PopOne(); break;
                }
                if ((cx == cDenorm || cy == cDenorm) && !E.DenormGate()) break;
                bool xs = (x.signExp >> 15) & 1, ys = (y.signExp >> 15) & 1;
                TransEnv();
                extFloat80_t r; bool inx = true;
                auto signed_ = [&](extFloat80_t v) { return ys ? Neg(v) : v; };
                if (cy == cInf) {
                    if (cx == cInf) r = signed_(xs ? g_tc.pi3O4 : g_tc.piO4);
                    else r = signed_(g_tc.piO2);
                } else if (cx == cInf) {
                    if (xs) r = signed_(g_tc.pi);
                    else { r = MakeExt((uint16_t)(ys ? 0x8000 : 0), 0); inx = false; }
                } else if (cy == cZero) {
                    if (xs) r = signed_(g_tc.pi);            // includes x = -0
                    else { r = MakeExt((uint16_t)(ys ? 0x8000 : 0), 0); inx = false; }
                } else if (cx == cZero) {
                    r = signed_(g_tc.piO2);
                } else {
                    extFloat80_t ax = x; ax.signExp &= 0x7FFF;
                    extFloat80_t ay = y; ay.signExp &= 0x7FFF;
                    extFloat80_t base;
                    if (!MagGT(ay, ax)) {                    // |y| <= |x|
                        base = AtanPos(extF80_div(ay, ax));
                        r = xs ? extF80_sub(g_tc.pi, base) : base;
                    } else {
                        base = AtanPos(extF80_div(ax, ay));
                        r = xs ? extF80_add(g_tc.piO2, base) : extF80_sub(g_tc.piO2, base);
                    }
                    r = signed_(r);
                }
                softfloat_exceptionFlags = 0;
                if (inx) F.flags |= kPE;
                if (((r.signExp & 0x7FFF) == 0) && r.signif) F.flags |= kUE;
                F.Put(1, r); F.PopOne();
                break;
            }
            case 0xFB:                                       // fsincos
            case 0xFE:                                       // fsin
            case 0xFF: {                                     // fcos
                F.c1 = 0;
                bool wantSin = (modrm != 0xFF);
                bool push = (modrm == 0xFB);
                if (F.Empty(0)) {
                    if (!E.StackFault(false)) break;
                    F.Put(0, kIndef);
                    if (push) { F.PushSlot(); F.Put(0, kIndef); }   // both results indef
                    break;
                }
                if (push) {
                    int destPhys = (F.top - 1) & 7;
                    if (!((F.empty >> destPhys) & 1)) {      // no room for the push
                        if (!E.StackFault(true)) break;
                        F.Put(0, kIndef);                    // old ST0 too (probed)
                        F.PushSlot(); F.Put(0, kIndef);
                        break;
                    }
                }
                extFloat80_t a = F.Get(0);
                Cls ca = ClassOf(a);
                if (ca == cUnsupp || ca == cSNaN || ca == cInf) {
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                    extFloat80_t r = (ca == cSNaN) ? Quieten(a) : kIndef;
                    F.Put(0, r);
                    if (push) E.PushVal(r);
                    F.c2 = 0;
                    break;
                }
                if (ca == cQNaN) {
                    F.Put(0, a);
                    if (push) E.PushVal(a);
                    F.c2 = 0;
                    break;
                }
                if (ca == cZero) {                           // exact
                    extFloat80_t sinv = a, cosv = kOne;
                    if (wantSin && !push) F.Put(0, sinv);
                    else if (!wantSin) F.Put(0, cosv);
                    else { F.Put(0, sinv); E.PushVal(cosv); }
                    F.c2 = 0;
                    break;
                }
                // |x| >= 2^63: unreduced, operand untouched
                if ((a.signExp & 0x7FFF) >= 0x403E) { F.c2 = 1; break; }
                if (ca == cDenorm && !E.DenormGate()) break;
                TransEnv();
                extFloat80_t sinv, cosv;
                SinCos(a, &sinv, &cosv);
                softfloat_exceptionFlags = 0;
                F.flags |= kPE;
                extFloat80_t chk = wantSin ? sinv : cosv;
                if (((chk.signExp & 0x7FFF) == 0) && chk.signif) F.flags |= kUE;
                if (wantSin && !push) F.Put(0, sinv);
                else if (!wantSin) F.Put(0, cosv);
                else { F.Put(0, sinv); E.PushVal(cosv); }
                F.c2 = 0;
                break;
            }
            default: decoded = false; break;
            }
        }
        break;

    // ------------------------------------------------------------------ DA
    case 0xDA:
        if (mod != 3) {                            // fiadd/fimul/ficom/ficomp/... m32int
            int32_t iv = (int32_t)Exec::Ld32(ea);
            softfloat_exceptionFlags = 0;
            extFloat80_t b = i32_to_extF80(iv);
            softfloat_exceptionFlags = 0;
            MemArith(reg, b, cNorm);
        } else if (modrm == 0xE9) {                // fucompp
            bool em = F.Empty(0) || F.Empty(1);
            extFloat80_t a = em ? kIndef : F.Get(0), b = em ? kIndef : F.Get(1);
            E.CompareOp(a, b, ClassOf(a), ClassOf(b), em ? 1 : 0, 2, true);
        } else decoded = false;
        break;

    // ------------------------------------------------------------------ DB
    case 0xDB:
        if (mod != 3) {
            switch (reg) {
            case 0: LoadInt((int32_t)Exec::Ld32(ea)); break; // fild m32
            case 2: StoreMemInt(32, false); break;           // fist m32
            case 3: StoreMemInt(32, true); break;            // fistp m32
            case 5: {                                        // fld m80 (raw, no exceptions)
                F.c1 = 0;
                int pc = E.PushCheck();
                if (pc != 2) break;
                extFloat80_t v;
                memcpy(&v.signif, (void*)(uintptr_t)ea, 8);
                memcpy(&v.signExp, (void*)(uintptr_t)(ea + 8), 2);
                E.PushVal(v);
                break;
            }
            case 7: {                                        // fstp m80 (raw)
                F.c1 = 0;
                if (F.Empty(0)) {
                    if (!E.StackFault(false)) break;
                    memcpy((void*)(uintptr_t)ea, &kIndef.signif, 8);
                    memcpy((void*)(uintptr_t)(ea + 8), &kIndef.signExp, 2);
                    F.PopOne(); break;
                }
                extFloat80_t v = F.Get(0);
                memcpy((void*)(uintptr_t)ea, &v.signif, 8);
                memcpy((void*)(uintptr_t)(ea + 8), &v.signExp, 2);
                F.PopOne();
                break;
            }
            default: decoded = false; break;
            }
        } else if (modrm == 0xE2) {                          // fnclex
            F.flags = 0;
        } else decoded = false;
        break;

    // ------------------------------------------------------------------ DC
    case 0xDC:
        if (mod != 3) {
            extFloat80_t b; Cls cb;
            LoadMemF64(&b, &cb);
            MemArith(reg, b, cb);
        } else {
            switch (reg) {
            case 0: RegArith(0, rm, rm, 0); break;           // fadd st(i),st
            case 1: RegArith(1, rm, rm, 0); break;           // fmul st(i),st
            case 4: RegArith(4, rm, rm, 0); break;           // fsubr st(i),st: st - st(i)...
            case 5: RegArith(5, rm, rm, 0); break;
            case 6: RegArith(6, rm, rm, 0); break;
            case 7: RegArith(7, rm, rm, 0); break;
            default: decoded = false; break;
            }
            // NOTE the DC register encodings reverse the mnemonic pair:
            //   DC E0+i = FSUBR ST(i),ST = ST0 - ST(i)  -> kind 4 (a - b)
            //   DC E8+i = FSUB  ST(i),ST = ST(i) - ST0  -> kind 5 (b - a)
            //   DC F0+i = FDIVR ST(i),ST = ST0 / ST(i)  -> kind 6 (a / b)
            //   DC F8+i = FDIV  ST(i),ST = ST(i) / ST0  -> kind 7 (b / a)
            // which is exactly the same kind numbering as D8 — no swap needed.
        }
        break;

    // ------------------------------------------------------------------ DD
    case 0xDD:
        if (mod != 3) {
            switch (reg) {
            case 0: {                                        // fld m64
                F.c1 = 0;
                int pc = E.PushCheck();
                if (pc != 2) break;
                uint64_t u = Exec::Ld64(ea);
                Cls c = ClassF64(u);
                softfloat_exceptionFlags = 0;
                float64_t f; f.v = u;
                extFloat80_t v = f64_to_extF80(f);
                uint8_t sf = (uint8_t)softfloat_exceptionFlags;
                softfloat_exceptionFlags = 0;
                if (c == cDenorm) { if (!E.DenormGate()) break; }
                if (sf & softfloat_flag_invalid) {
                    F.flags |= kIE;
                    if (!F.Masked(kIE)) break;
                }
                E.PushVal(v);
                break;
            }
            case 2: StoreMemFp(true, false); break;          // fst m64
            case 3: StoreMemFp(true, true); break;           // fstp m64
            case 7: {                                        // fnstsw m16 (no-wait)
                uint16_t sw = (uint16_t)(F.flags | (F.c0 << 8) | (F.c1 << 9) |
                                         (F.c2 << 10) | (F.top << 11) | (F.c3 << 14));
                if ((F.flags & ~F.cw) & 0x3F) sw |= 0x8080;
                Exec::St16(ea, sw);
                break;
            }
            default: decoded = false; break;
            }
        } else {
            switch (reg) {
            case 0:                                          // ffree st(i)
                F.c1 = 0;
                F.empty |= 1u << F.Phys(rm);
                break;
            case 2: case 3: {                                // fst/fstp st(i)
                F.c1 = 0;
                if (F.Empty(0)) {
                    if (!E.StackFault(false)) break;
                    F.Put(rm, kIndef);
                    if (reg == 3) F.PopOne();
                    break;
                }
                F.Put(rm, F.Get(0));
                if (reg == 3) F.PopOne();
                break;
            }
            case 4: case 5: {                                // fucom/fucomp st(i)
                bool em = F.Empty(0) || F.Empty(rm);
                extFloat80_t a = em ? kIndef : F.Get(0), b = em ? kIndef : F.Get(rm);
                E.CompareOp(a, b, ClassOf(a), ClassOf(b), em ? 1 : 0,
                            reg == 5 ? 1 : 0, true);
                break;
            }
            default: decoded = false; break;
            }
        }
        break;

    // ------------------------------------------------------------------ DE
    case 0xDE:
        if (mod != 3) {                            // integer arith m16
            int32_t iv = (int16_t)Exec::Ld16(ea);
            softfloat_exceptionFlags = 0;
            extFloat80_t b = i32_to_extF80(iv);
            softfloat_exceptionFlags = 0;
            MemArith(reg, b, cNorm);
        } else if (modrm == 0xD9) {                // fcompp
            bool em = F.Empty(0) || F.Empty(1);
            extFloat80_t a = em ? kIndef : F.Get(0), b = em ? kIndef : F.Get(1);
            E.CompareOp(a, b, ClassOf(a), ClassOf(b), em ? 1 : 0, 2, false);
        } else {
            switch (reg) {
            case 0: RegArith(0, rm, rm, 1); break;           // faddp
            case 1: RegArith(1, rm, rm, 1); break;           // fmulp
            case 4: RegArith(4, rm, rm, 1); break;           // fsubrp: ST0 - ST(i)
            case 5: RegArith(5, rm, rm, 1); break;           // fsubp:  ST(i) - ST0
            case 6: RegArith(6, rm, rm, 1); break;           // fdivrp: ST0 / ST(i)
            case 7: RegArith(7, rm, rm, 1); break;           // fdivp:  ST(i) / ST0
            default: decoded = false; break;
            }
        }
        break;

    // ------------------------------------------------------------------ DF
    case 0xDF:
        if (mod != 3) {
            switch (reg) {
            case 0: LoadInt((int16_t)Exec::Ld16(ea)); break; // fild m16
            case 2: StoreMemInt(16, false); break;           // fist m16
            case 3: StoreMemInt(16, true); break;            // fistp m16
            case 5: LoadInt((int64_t)Exec::Ld64(ea)); break; // fild m64
            case 7: StoreMemInt(64, true); break;            // fistp m64
            default: decoded = false; break;
            }
        } else if (modrm == 0xE0) {                          // fnstsw ax (no-wait)
            uint16_t sw = (uint16_t)(F.flags | (F.c0 << 8) | (F.c1 << 9) |
                                     (F.c2 << 10) | (F.top << 11) | (F.c3 << 14));
            if ((F.flags & ~F.cw) & 0x3F) sw |= 0x8080;
            s.r[EAX] = (s.r[EAX] & 0xFFFF0000u) | sw;
        } else decoded = false;
        break;

    default:
        decoded = false;
        break;
    }

    if (!decoded) return 0;                        // BadDecode: image untouched
    StoreImage(F, s.fpu.image);
    return 1;
}

void X87ExactOnImage(uint8_t image[108], uint8_t op, uint8_t modrm, uint32_t ea,
                     int* outcome) {
    CpuState s{};
    memcpy(s.fpu.image, image, 108);
    int r = X87ExactExec(s, op, modrm, ea);
    memcpy(image, s.fpu.image, 108);
    if (outcome) *outcome = r;
}

