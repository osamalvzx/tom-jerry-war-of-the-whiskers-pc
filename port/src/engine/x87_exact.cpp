// int-store helpers with the "invalid supersedes PE" x87 rule (probed)
struct IntCvt { uint64_t val; bool invalid; bool inexact; bool up; };

static IntCvt CvtToI32(extFloat80_t v, uint8_t rc) {
    IntCvt r{};
    softfloat_roundingMode = rc; softfloat_exceptionFlags = 0;
    int32_t a = (int32_t)extF80_to_i32(v, rc, true);
    uint8_t sf = (uint8_t)softfloat_exceptionFlags;
    r.invalid = (sf & softfloat_flag_invalid) != 0;
    r.inexact = (sf & softfloat_flag_inexact) != 0;
    r.val = (uint64_t)(int64_t)a;
    if (!r.invalid && r.inexact) {
        softfloat_exceptionFlags = 0;
        int32_t b = (int32_t)extF80_to_i32(v, softfloat_round_minMag, false);
        uint64_t ma = a < 0 ? (uint64_t)(-(int64_t)a) : (uint64_t)a;
        uint64_t mb = b < 0 ? (uint64_t)(-(int64_t)b) : (uint64_t)b;
        r.up = ma > mb;
    }
    softfloat_exceptionFlags = 0;
    return r;
}
static IntCvt CvtToI64(extFloat80_t v, uint8_t rc) {
    IntCvt r{};
    softfloat_roundingMode = rc; softfloat_exceptionFlags = 0;
    int64_t a = (int64_t)extF80_to_i64(v, rc, true);
    uint8_t sf = (uint8_t)softfloat_exceptionFlags;
    r.invalid = (sf & softfloat_flag_invalid) != 0;
    r.inexact = (sf & softfloat_flag_inexact) != 0;
    r.val = (uint64_t)a;
    if (!r.invalid && r.inexact) {
        softfloat_exceptionFlags = 0;
        int64_t b = (int64_t)extF80_to_i64(v, softfloat_round_minMag, false);
        uint64_t ma = a < 0 ? (uint64_t)(-a) : (uint64_t)a;
        uint64_t mb = b < 0 ? (uint64_t)(-b) : (uint64_t)b;
        r.up = ma > mb;
    }
    softfloat_exceptionFlags = 0;
    return r;
}

// f32/f64 raw operand classification
static Cls ClassF32(uint32_t u) {
    uint32_t exp = (u >> 23) & 0xFF, frac = u & 0x7FFFFF;
    if (exp == 0xFF) return frac ? ((frac & 0x400000) ? cQNaN : cSNaN) : cInf;
    if (exp == 0) return frac ? cDenorm : cZero;
    return cNorm;
}
static Cls ClassF64(uint64_t u) {
    uint32_t exp = (uint32_t)(u >> 52) & 0x7FF; uint64_t frac = u & 0xFFFFFFFFFFFFFull;
    if (exp == 0x7FF) return frac ? ((frac & 0x8000000000000ull) ? cQNaN : cSNaN) : cInf;
    if (exp == 0) return frac ? cDenorm : cZero;
    return cNorm;
}

