struct TransConsts {
    extFloat80_t invFact[23];     // 1/k!  (k = 1..22; factorials exact in 64 bits)
    extFloat80_t invOdd[16];      // 1/(2k+1), k = 1..15
    extFloat80_t pi, piO2, piO4, pi3O4;
    extFloat80_t ln2, twoOverLn2, sqrt2;
};
static TransConsts g_tc;
static bool g_tcInit = false;

static void InitTrans() {
    if (g_tcInit) return;
    g_tcInit = true;
    softfloat_roundingMode = softfloat_round_near_even;
    extF80_roundingPrecision = 80;
    softfloat_exceptionFlags = 0;
    extFloat80_t f = kOne;
    g_tc.invFact[1] = kOne;
    for (int k = 2; k <= 22; ++k) {
        f = extF80_mul(f, i32_to_extF80(k));               // exact through 22!
        g_tc.invFact[k] = extF80_div(kOne, f);
    }
    for (int k = 1; k <= 15; ++k)
        g_tc.invOdd[k] = extF80_div(kOne, i32_to_extF80(2 * k + 1));
    // RN-rounded x87 constant family (host-verified patterns, see header comment)
    g_tc.pi    = MakeExt(0x4000, 0xC90FDAA22168C235ull);
    g_tc.piO2  = MakeExt(0x3FFF, 0xC90FDAA22168C235ull);
    g_tc.piO4  = MakeExt(0x3FFE, 0xC90FDAA22168C235ull);
    g_tc.pi3O4 = extF80_mul(g_tc.piO4, i32_to_extF80(3));
    g_tc.ln2   = MakeExt(0x3FFE, 0xB17217F7D1CF79ACull);
    g_tc.twoOverLn2 = MakeExt(0x4000, 0xB8AA3B295C17F0BCull);   // 2*log2(e), RN
    g_tc.sqrt2 = extF80_sqrt(MakeExt(0x4000, 0x8000000000000000ull));
    softfloat_exceptionFlags = 0;
}

// RN/80 environment for all internal transcendental math
static void TransEnv() {
    softfloat_roundingMode = softfloat_round_near_even;
    extF80_roundingPrecision = 80;
    softfloat_exceptionFlags = 0;
}

static extFloat80_t Neg(extFloat80_t v) { v.signExp ^= 0x8000; return v; }
static extFloat80_t Quieten(extFloat80_t v) { v.signif |= 0x4000000000000000ull; return v; }

// Horner: sum c[i] * x^i, i = 0..n-1
static extFloat80_t Poly(const extFloat80_t* c, int n, extFloat80_t x) {
    extFloat80_t s = c[n - 1];
    for (int i = n - 2; i >= 0; --i)
        s = extF80_add(extF80_mul(s, x), c[i]);
    return s;
}

// sin(r) / cos(r) kernels for |r| <= pi/4 (+ rounding slop)
static extFloat80_t SinKernel(extFloat80_t r) {
    extFloat80_t c[11], u = extF80_mul(r, r);
    c[0] = kOne;
    for (int k = 1; k <= 10; ++k) {
        c[k] = g_tc.invFact[2 * k + 1];
        if (k & 1) c[k] = Neg(c[k]);
    }
    return extF80_mul(r, Poly(c, 11, u));
}
static extFloat80_t CosKernel(extFloat80_t r) {
    extFloat80_t c[12], u = extF80_mul(r, r);
    c[0] = kOne;
    for (int k = 1; k <= 11; ++k) {
        c[k] = g_tc.invFact[2 * k];
        if (k & 1) c[k] = Neg(c[k]);
    }
    return Poly(c, 12, u);
}

// ---- 192-bit fixed-point trig reduction (the x87's own 66-bit pi/2) --------------

struct U192 { uint64_t w[3]; };                    // w[0] low

static bool GE192(const U192& a, const U192& b) {
    for (int i = 2; i >= 0; --i) {
        if (a.w[i] != b.w[i]) return a.w[i] > b.w[i];
    }
    return true;
}
static void Sub192(U192& a, const U192& b) {
    uint64_t borrow = 0;
    for (int i = 0; i < 3; ++i) {
        uint64_t d = a.w[i] - b.w[i];
        uint64_t br2 = (d > a.w[i]) ? 1u : 0u;
        uint64_t d2 = d - borrow;
        if (d2 > d) br2 = 1;
        a.w[i] = d2; borrow = br2;
    }
}
static void Shr1(U192& a) {
    a.w[0] = (a.w[0] >> 1) | (a.w[1] << 63);
    a.w[1] = (a.w[1] >> 1) | (a.w[2] << 63);
    a.w[2] >>= 1;
}
static void Shl192(U192& a, int k) {              // k in [0, 127]
    while (k >= 64) { a.w[2] = a.w[1]; a.w[1] = a.w[0]; a.w[0] = 0; k -= 64; }
    if (k) {
        a.w[2] = (a.w[2] << k) | (a.w[1] >> (64 - k));
        a.w[1] = (a.w[1] << k) | (a.w[0] >> (64 - k));
        a.w[0] <<= k;
    }
}

// hardware's 66-bit pi/2, as (value * 2^127): 0xC90FDAA22168C234C << 61
static const U192 kP192 = { { 0xC000000000000000ull, 0xC90FDAA22168C234ull, 0 } };

struct Red { int q; extFloat80_t r; };             // |x| = n*(pi/2)66 + r, q = n&3

// requires 2^-2 <= |x| < 2^63 normalized (sig has bit 63); e = unbiased exponent
static Red ReduceTrig(uint64_t sig, int e) {
    U192 X = { { sig, 0, 0 } };
    Shl192(X, e + 64);                             // X = |x| * 2^127
    U192 S = kP192;
    Shl192(S, 62);
    uint64_t n = 0;
    for (int i = 62; i >= 0; --i) {
        n <<= 1;
        if (GE192(X, S)) { Sub192(X, S); n |= 1; }
        Shr1(S);
    }
    // X = remainder in [0, P): round n to nearest (tie -> even)
    U192 half = kP192; Shr1(half);
    bool negR = false;
    bool gtHalf = GE192(X, half) && !(X.w[0] == half.w[0] && X.w[1] == half.w[1] && X.w[2] == half.w[2]);
    bool eqHalf = (X.w[0] == half.w[0] && X.w[1] == half.w[1] && X.w[2] == half.w[2]);
    if (gtHalf || (eqHalf && (n & 1))) {
        U192 t = kP192; Sub192(t, X); X = t;
        n += 1; negR = true;
    }
    Red out; out.q = (int)(n & 3);
    // convert X * 2^-127 (X < 2^128) to extF80, round to nearest-even
    if (!X.w[0] && !X.w[1]) { out.r = MakeExt(0, 0); return out; }
    int t;
    if (X.w[1]) { t = 127; while (!((X.w[1] >> (t - 64)) & 1)) --t; }
    else        { t = 63;  while (!((X.w[0] >> t) & 1)) --t; }
    uint64_t rsig; bool inc = false;
    if (t >= 64) {
        int sh = t - 63;                           // 1..64
        uint64_t rbit, sticky;
        if (sh == 64) {
            rsig = X.w[1];
            rbit = (X.w[0] >> 63) & 1;
            sticky = X.w[0] & 0x7FFFFFFFFFFFFFFFull;
        } else {
            rsig = (X.w[1] << (64 - sh)) | (X.w[0] >> sh);
            rbit = (X.w[0] >> (sh - 1)) & 1;
            sticky = (sh > 1) ? (X.w[0] & ((1ull << (sh - 1)) - 1)) : 0;
        }
        inc = rbit && (sticky || (rsig & 1));
    } else {
        rsig = X.w[0] << (63 - t);
    }
    int be = (t - 127) + 0x3FFF;
    if (inc) { ++rsig; if (!rsig) { rsig = 0x8000000000000000ull; ++be; } }
    out.r = MakeExt((uint16_t)((negR ? 0x8000 : 0) | be), rsig);
    return out;
}

// full sin+cos of a finite nonzero non-denormal-exempt |x| < 2^63.
// sign = sign of x.  Everything RN/80.
static void SinCos(extFloat80_t x, extFloat80_t* sinOut, extFloat80_t* cosOut) {
    bool neg = (x.signExp >> 15) & 1;
    int exp = x.signExp & 0x7FFF; uint64_t sig = x.signif;
    if (!exp) exp = 1;
    if (!(sig >> 63)) {
        struct exp32_sig64 nz = softfloat_normSubnormalExtF80Sig(sig);
        exp += nz.exp; sig = nz.sig;
    }
    int e = exp - 0x3FFF;
    extFloat80_t s, c;
    if (e <= -2) {                                 // |x| < 0.5 < pi/4: no reduction
        extFloat80_t ax = x; ax.signExp &= 0x7FFF;  // (possibly denormal — kernel is fine)
        s = SinKernel(ax); c = CosKernel(ax);
    } else {
        Red rd = ReduceTrig(sig, e);
        extFloat80_t ks = SinKernel(rd.r), kc = CosKernel(rd.r);
        switch (rd.q) {
        case 0: s = ks;      c = kc;      break;
        case 1: s = kc;      c = Neg(ks); break;
        case 2: s = Neg(ks); c = Neg(kc); break;
        default: s = Neg(kc); c = ks;     break;
        }
    }
    if (neg) s = Neg(s);
    *sinOut = s; *cosOut = c;
}

// atan(u) for 0 <= u <= 1 (RN/80): four half-angle steps + odd Taylor deg 15, x16
static extFloat80_t AtanPos(extFloat80_t u) {
    for (int k = 0; k < 4; ++k) {
        extFloat80_t t = extF80_add(kOne, extF80_mul(u, u));
        t = extF80_add(kOne, extF80_sqrt(t));
        u = extF80_div(u, t);
    }
    extFloat80_t c[8], u2 = extF80_mul(u, u);
    c[0] = kOne;
    for (int k = 1; k <= 7; ++k) {
        c[k] = g_tc.invOdd[k];
        if (k & 1) c[k] = Neg(c[k]);
    }
    extFloat80_t a = extF80_mul(u, Poly(c, 8, u2));
    return ScaleExact2k(a, 4);
}

// log2(x) for finite positive non-zero x (RN/80)
static extFloat80_t Log2Pos(extFloat80_t x) {
    int exp = x.signExp & 0x7FFF; uint64_t sig = x.signif;
    if (!exp) exp = 1;
    if (!(sig >> 63)) {
        struct exp32_sig64 nz = softfloat_normSubnormalExtF80Sig(sig);
        exp += nz.exp; sig = nz.sig;
    }
    int e = exp - 0x3FFF;
    extFloat80_t m = MakeExt(0x3FFF, sig);         // [1, 2)
    if (extF80_lt(g_tc.sqrt2, m)) { m = MakeExt(0x3FFE, sig); e += 1; }
    extFloat80_t s = extF80_div(extF80_sub(m, kOne), extF80_add(m, kOne));
    extFloat80_t c[14], s2 = extF80_mul(s, s);
    c[0] = kOne;
    for (int k = 1; k <= 13; ++k) c[k] = g_tc.invOdd[k];
    extFloat80_t L = extF80_mul(s, Poly(c, 14, s2));   // artanh(s) = ln(m)/2
    L = extF80_mul(L, g_tc.twoOverLn2);                // log2(m)
    return extF80_add(i32_to_extF80(e), L);
}

// expm1 kernel: 2^x - 1 = expm1(x*ln2), Taylor deg 20 (RN/80)
static extFloat80_t Expm1Pow2(extFloat80_t x) {
    extFloat80_t t = extF80_mul(x, g_tc.ln2);
    extFloat80_t c[20];
    for (int k = 0; k < 20; ++k) c[k] = g_tc.invFact[k + 1];
    return extF80_mul(t, Poly(c, 20, t));
}

